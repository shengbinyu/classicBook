def P(orig, trans, notes_list):
    notes = []
    for ref, note in (notes_list or []):
        if not ref:
            continue
        idx = orig.find(ref)
        if idx >= 0:
            notes.append({'pos': idx, 'len': len(ref), 'ref': ref, 'note': note})
    return {
        'pid': None,   # 后补
        'original': orig,
        'translation': trans or '',
        'notes': notes,
    }

def ch(id_, title, pid_prefix, triples):
    paragraphs = []
    for i, t in enumerate(triples, 1):
        orig, trans, notes_list = t
        p = P(orig, trans, notes_list)
        p['pid'] = f'{pid_prefix}-{i}'
        paragraphs.append(p)
    return {'id': id_, 'title': title, 'paragraphs': paragraphs}

